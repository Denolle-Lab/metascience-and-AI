#!/usr/bin/env python3
"""Write the decision-tree figure in decision-tree.qmd from agents/controller/decision-tree.json.

The JSON file is the controller's single source; the book's HTML is generated. --check reports
whether the page is in sync without writing.
"""
from __future__ import annotations
import argparse, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'agents' / 'controller' / 'decision-tree.json'
PAGE = ROOT / 'decision-tree.qmd'
BEGIN, END = '<!-- tree:begin (generated by tools/build_tree.py) -->', '<!-- tree:end -->'


def box(b: dict) -> str:
    if b['kind'] == 'back' and not b.get('name'):
        return f'<div class="dt-mode dt-back"><span class="dt-ret">{b["ret"]}</span></div>'
    cls = {'mode': 'dt-mode', 'back': 'dt-mode dt-back', 'esc': 'dt-mode dt-esc', 'end': 'dt-mode dt-end'}[b['kind']]
    nodes = f' <span class="dt-nodes">{b["nodes"]}</span>' if b.get('nodes') else ''
    ret = f'<span class="dt-ret">{b["ret"]}</span>' if b.get('ret') else ''
    return f'<div class="{cls}"><b>{b["name"]}</b>{nodes}<br/>{b["note"]}{ret}</div>'


def render(tree: dict) -> str:
    h = ['::: {#fig-tree .column-body-outset}', '', '```{=html}', '<div class="dtree">', f'<div class="dt-start">{tree["start"]}</div>']
    for q in tree['questions']:
        h.append('<div class="dt-row">')
        h.append(f'<div class="dt-q"><span class="dt-n">{q["n"]}</span><div><b>{q["q"]}</b><br/><span class="dt-sub">{q["sub"]}</span></div></div>')
        h.append('<div class="dt-branches">' + ''.join(f'<div class="dt-br"><span class="dt-lab">{b["label"]}</span>{box(b)}</div>' for b in q['branches']) + '</div>')
        h.append('</div>')
        h.append(f'<div class="dt-down"><span>{q["down"]}</span></div>')
    h += [f'<div class="dt-keep">{tree["end"]}</div>', '</div>', '```', '', f'{tree["caption"]} Source: `agents/controller/decision-tree.json`, v{tree["version"]}.', ':::']
    return '\n'.join(h)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    tree = json.loads(SRC.read_text())
    page = PAGE.read_text()
    if BEGIN not in page or END not in page:
        print(f'FAIL: {PAGE.name} lacks the tree markers', file=sys.stderr)
        return 1
    a, b = page.index(BEGIN) + len(BEGIN), page.index(END)
    new = page[:a] + '\n' + render(tree) + '\n' + page[b:]
    if args.check:
        if new != page:
            print('FAIL: decision-tree.qmd is out of date; run tools/build_tree.py', file=sys.stderr)
            return 1
        return 0
    PAGE.write_text(new)
    print(f'decision-tree.qmd written from v{tree["version"]}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
